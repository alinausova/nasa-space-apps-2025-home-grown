// Russian. Polite "вы", lower-case. Terms follow the shared glossary.

const rules = new Intl.PluralRules('ru');
/** one: 1, 21; few: 2–4, 22–24; many: 0, 5–20, 25; fractions take the few form (2,5 дня). */
const plural = (n: number, one: string, few: string, many: string) => {
  const form = rules.select(n);
  return form === 'one' ? one : form === 'many' ? many : few;
};
/** Genitive after "из", "от", "около": singular for 1, 21 and fractions, plural otherwise. */
const gen = (n: number, singular: string, pluralForm: string) => {
  const form = rules.select(n);
  return form === 'one' || form === 'other' ? singular : pluralForm;
};
/** Reads a number formatted for Russian ("1 200", "5,3") back, for plurals. */
